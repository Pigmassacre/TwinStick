def rgba(s):
    s = PALETTE[s] if len(s) == 1 else s
    return (int(s[0:2], 16), int(s[2:4], 16), int(s[4:6], 16), 255)


def parse(text):
    """A frame of text as (colours, glow) images."""
    rows = [r.strip() for r in text.strip().split("\n")]
    w = max(len(r) for r in rows)
    h = len(rows)
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    glow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == ".":
                continue
            im.putpixel((x, y), rgba(c))
            if c in GLOW:
                glow.putpixel((x, y), rgba(c))
    return im, glow


def outlined(im):
    """Adds the dark outline around everything that isn't transparent."""
    out = Image.new("RGBA", (im.width, im.height), (0, 0, 0, 0))
    px = im.load()
    op = out.load()
    for y in range(im.height):
        for x in range(im.width):
            if px[x, y][3]:
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < im.width and 0 <= ny < im.height and px[nx, ny][3]:
                    op[x, y] = OUTLINE
                    break
    out.alpha_composite(im)
    return out


def frame(text, outline=True):
    im, glow = parse(text)
    return (outlined(im) if outline else im, glow)


def fit(pair, w, h, feet_gap=1):
    """Sets a frame on a canvas w by h, in the middle, with its bottom `feet_gap` from the floor."""
    im, glow = pair
    canvas = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    canvas_g = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    bbox = im.getbbox() or (0, 0, im.width, im.height)
    x = (w - (bbox[2] - bbox[0])) // 2 - bbox[0]
    y = h - feet_gap - bbox[3]
    canvas.alpha_composite(im, (max(x, 0), max(y, 0)), (max(-x, 0), max(-y, 0)))
    canvas_g.alpha_composite(glow, (max(x, 0), max(y, 0)), (max(-x, 0), max(-y, 0)))
    return canvas, canvas_g


def add_sheet(name, frames, w, h, feet=1, anims=None, cols=None):
    """`frames` are (image, glow) pairs w by h. `anims` are name: (first, count, fps, loops)."""
    cols = cols or min(len(frames), 16)
    rows = math.ceil(len(frames) / cols)
    sheet = Image.new("RGBA", (w * cols, h * rows), (0, 0, 0, 0))
    glow = Image.new("RGB", (w * cols, h * rows), (0, 0, 0))
    any_glow = False
    for i, (im, g) in enumerate(frames):
        at = ((i % cols) * w, (i // cols) * h)
        sheet.alpha_composite(im, at)
        if g is not None and g.getbbox():
            glow.paste(g.convert("RGB"), at, g)
            any_glow = True
    sheet.save(os.path.join(OUT, name + ".png"))
    glow_path = os.path.join(OUT, name + "_e.png")
    if any_glow:
        glow.save(glow_path)
    elif os.path.exists(glow_path):
        os.remove(glow_path)
    SHEETS[name] = {"w": w, "h": h, "cols": cols, "rows": rows, "feet": feet, "anims": anims or {"idle": (0, len(frames), 6, True)}}


def text_sheet(name, frames, w=16, h=16, feet=1, anims=None, outline=True, cols=None):
    add_sheet(name, [fit(frame(t, outline), w, h, feet) for t in frames], w, h, feet, anims, cols)


# ---------------------------------------------------------------- the ranger

def ranger():
    d = os.path.join(ORIG, "ranger")

    def load(n):
        return Image.open(os.path.join(d, n + ".png")).convert("RGBA")
    idle = [load(f"idle_{i:02d}") for i in range(10)]
    run = [load(f"run_{i:02d}") for i in range(8)]
    attack = [load(f"attack_{i:02d}") for i in range(13)]

    def mix(top, bottom, split=11):
        out = bottom.copy()
        out.paste(top.crop((0, 0, 20, split)), (0, 0))
        return out
    # Running while drawing, and running having just let go: the original's
    # attack from the belt up, its run from the belt down.
    run_draw = [mix(attack[3], run[i]) for i in range(8)]
    run_loose = [mix(attack[7], run[i]) for i in range(8)]
    # A second ranger, for the roll: the cloak thrown forward, low to the ground.
    all_frames = idle + run + attack + run_draw + run_loose
    anims = {
        "idle": (0, 10, 8, True),
        "run": (10, 8, 14, True),
        "attack": (18, 13, 26, False),
        "draw": (21, 1, 1, True),
        "loose": (25, 1, 1, True),
        "run_draw": (31, 8, 14, True),
        "run_loose": (39, 8, 14, True),
    }
    add_sheet("ranger", [(f, None) for f in all_frames], 20, 16, 0, anims, cols=13)
    # The UI's: the portrait and the two stances.
    load("portrait").save(os.path.join(OUT, "portrait.png"))
    Image.open(os.path.join(d, "stances", "aim.png")).convert("RGBA").save(os.path.join(OUT, "stance_aim.png"))
    Image.open(os.path.join(d, "stances", "demolition.png")).convert("RGBA").save(os.path.join(OUT, "stance_demolition.png"))


