def shaded_ellipse(draw, box, cols):
    """An ellipse lit from the top left: a few nested rings, darkest outside."""
    x0, y0, x1, y1 = box
    n = len(cols)
    for i, col in enumerate(cols):
        t = i / max(n, 1)
        inset_x = (x1 - x0) * 0.5 * t
        inset_y = (y1 - y0) * 0.5 * t
        dx = -(x1 - x0) * 0.08 * t
        dy = -(y1 - y0) * 0.1 * t
        draw.ellipse((x0 + inset_x + dx, y0 + inset_y + dy, x1 - inset_x + dx, y1 - inset_y + dy), fill=rgba(col))


