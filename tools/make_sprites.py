def logo():
    """The title: Bungee, burning from the bottom up, with firedamp hanging about it."""
    rng = random.Random(12)
    size = 40
    path = None
    folder = REPO
    while folder != os.path.dirname(folder):
        folder = os.path.dirname(folder)
        candidate = os.path.join(folder, "Assets", "Fonts", "Bungee", "Bungee-Regular.ttf")
        if os.path.isfile(candidate):
            path = candidate
            break
    font = ImageFont.truetype(path, size)
    text = "FIREDAMP"
    w = int(font.getlength(text)) + 24
    h = size + 26
    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    draw.fontmode = "1"
    draw.text((12, 14), text, font=font, fill=255)
    letters = mask.point(lambda v: 255 if v > 127 else 0)
    bbox = letters.getbbox()
    frames = []
    ramp = ["fff2c0", "ffe27a", "ffb347", "ff7a24", "c44312", "941919", "5c1010"]
    for f in range(4):
        im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        glow = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        lp = letters.load()
        top, bottom = bbox[1], bbox[3]
        for y in range(h):
            for x in range(w):
                if not lp[x, y]:
                    continue
                # Hotter toward the bottom, cooler at the top, the join between them wandering.
                t = (y - top) / max(bottom - top - 1, 1)
                wob = math.sin(x * 0.45 + f * 1.57) * 0.07 + math.sin(x * 0.17 - f * 1.57) * 0.05
                v = 1.0 - t + wob + (rng.random() - 0.5) * 0.09
                i = max(0, min(len(ramp) - 1, int(v * len(ramp))))
                c = rgba(ramp[i])
                im.putpixel((x, y), c)
                if i <= 2:
                    glow.putpixel((x, y), c)
        # Flames licking up off the tops of the letters.
        tongues = random.Random(f * 3 + 1)
        for x in range(bbox[0], bbox[2]):
            for y in range(top, bottom):
                if lp[x, y]:
                    if tongues.random() < 0.11:
                        for k in range(tongues.randrange(1, 7)):
                            ty = y - k - 1
                            if ty >= 0 and not lp[x, ty]:
                                c = rgba(ramp[min(3 + k // 2, 6)])
                                im.putpixel((x, ty), c)
                    break
        frames.append((outlined(outlined(im)), glow))
    add_sheet("logo", frames, w, h, 0, {"idle": (0, 4, 7, True)}, cols=2)


def write_table():
    lines = [
        "class_name Sheets",
        "## Every sprite sheet. Written by tools/make_sprites.py: not to be edited by hand.",
        "## w, h: a frame's size. cols, rows: the frames in the sheet. feet: how far up from",
        "## the frame's bottom its pivot is. anims: name -> [first frame, count, fps, loops].",
        "",
        "const ALL := {",
    ]
    for name, s in SHEETS.items():
        anims = ", ".join(f'"{k}": [{v[0]}, {v[1]}, {v[2]}, {"true" if v[3] else "false"}]' for k, v in s["anims"].items())
        lines.append(f'\t"{name}": {{"w": {s["w"]}, "h": {s["h"]}, "cols": {s["cols"]}, "rows": {s["rows"]}, "feet": {s["feet"]}, "anims": {{{anims}}}}},')
    lines.append("}")
    with open(os.path.join(REPO, "src", "data", "sheets.gd"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


