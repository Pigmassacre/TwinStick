def noise_circle(rng, size, radius, inner, cols):
    im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    c = size / 2.0
    for y in range(size):
        for x in range(size):
            d = math.hypot(x + 0.5 - c, y + 0.5 - c)
            if d > radius + rng.random() * 2.0 - 1.0:
                continue
            if d < inner:
                continue
            t = d / max(radius, 0.001)
            i = min(len(cols) - 1, int(t * len(cols) + rng.random() * 0.8))
            im.putpixel((x, y), rgba(cols[i]))
    return im


